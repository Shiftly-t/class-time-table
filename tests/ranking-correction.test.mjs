import assert from 'node:assert/strict';
import {planDateCorrection} from '../ranking-correction.mjs';
const date='2026-11-25',now='2026-11-26T12:00:00+09:00';
const fact=(studentId,teacherUid,start='17:30',end='18:25')=>({slotId:JSON.stringify([studentId,date,start,end]),studentId,teacherUid,date,endedAt:date+'T'+end+':00+09:00',kind:'regular',status:'done'});
const a=fact('s1','a'),b=fact('s2','a'),historic=fact('historic','a'),unrelated=fact('historic','c');
const current={date,revision:1,facts:[a,b,historic]};
const run=(beforeFacts,afterFacts,over={})=>planDateCorrection({date,now,current,beforeFacts,afterFacts,actor:'manager',actorRole:'admin',operationId:'fix-1',reason:'授業訂正',...over});
const moved={...a,teacherUid:'b'};
const p=run([a,b,unrelated],[moved,unrelated]);
assert.equal(p.result.day.facts.length,2);
assert.equal(p.result.day.facts.find(x=>x.studentId==='historic').teacherUid,'a');
assert.equal(p.result.day.facts.find(x=>x.studentId==='s1').teacherUid,'b');
assert.deepEqual(p.result.refresh.delta.map(x=>[x.teacherUid,x.slots]),[['a',-2],['b',1]]);
assert.equal(run([a],[{...a,memo:'changed'}]).state,'unchanged');
const later=fact('s1','a','18:30','19:25');
assert.equal(run([a],[later]).result.day.facts.find(x=>x.studentId==='s1').slotId,later.slotId);
assert.equal(run([], [fact('s3','a')]).result.day.facts.length,4);
assert.throws(()=>run([unrelated],[]),/BASELINE_CONFLICT/);
assert.throws(()=>run([], [a]),/BASELINE_CONFLICT/);
assert.throws(()=>run([a],[moved],{actorRole:'employee'}),/FORBIDDEN/);
assert.throws(()=>run([a],[moved],{current:null}),/DAY_NOT_CAPTURED/);
assert.throws(()=>run([], [fact('s1','a','18:00','19:00')]),/OVERLAPPING_STUDENT_SLOT/);
assert.equal(current.facts[0].teacherUid,'a');
console.log('SUCCESS RANKING DATE CORRECTION TESTS');
